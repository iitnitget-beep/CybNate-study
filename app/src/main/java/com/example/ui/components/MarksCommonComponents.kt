@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun MarksTopAppBar(
    title: String,
    subtitle: String? = null,
    onBackClick: (() -> Unit)? = null,
    actions: @Composable () -> Unit = {}
) {
    TopAppBar(
        title = {
            Column {
                Text(
                    text = title,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
                if (!subtitle.isNullOrBlank()) {
                    Text(
                        text = subtitle,
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis
                    )
                }
            }
        },
        navigationIcon = {
            if (onBackClick != null) {
                IconButton(
                    onClick = onBackClick,
                    modifier = Modifier.testTag("appbar_back_button")
                ) {
                    Icon(
                        imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                        contentDescription = "Back"
                    )
                }
            }
        },
        actions = { actions() },
        colors = TopAppBarDefaults.topAppBarColors(
            containerColor = MaterialTheme.colorScheme.surface,
            titleContentColor = MaterialTheme.colorScheme.onSurface
        )
    )
}

@Composable
fun PaletteColorHelper(status: QuestionPaletteStatus): Pair<Color, Color> {
    return when (status) {
        QuestionPaletteStatus.NOT_VISITED -> Pair(MarksNotVisited.copy(alpha = 0.2f), Slate600)
        QuestionPaletteStatus.NOT_ANSWERED -> Pair(MarksError.copy(alpha = 0.2f), MarksError)
        QuestionPaletteStatus.ANSWERED -> Pair(MarksSuccess, Color.White)
        QuestionPaletteStatus.MARKED_FOR_REVIEW -> Pair(MarksPurple, Color.White)
        QuestionPaletteStatus.ANSWERED_AND_MARKED -> Pair(MarksPurple, Color.White)
    }
}

@Composable
fun PaletteStatusLegendItem(
    label: String,
    count: Int,
    backgroundColor: Color,
    textColor: Color,
    showDot: Boolean = false
) {
    Row(
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(6.dp),
        modifier = Modifier.padding(vertical = 4.dp)
    ) {
        Box(
            modifier = Modifier
                .size(24.dp)
                .clip(CircleShape)
                .background(backgroundColor),
            contentAlignment = Alignment.Center
        ) {
            Text(
                text = count.toString(),
                color = textColor,
                fontSize = 11.sp,
                fontWeight = FontWeight.Bold
            )
            if (showDot) {
                Box(
                    modifier = Modifier
                        .size(6.dp)
                        .clip(CircleShape)
                        .background(MarksSuccess)
                        .align(Alignment.BottomEnd)
                )
            }
        }
        Text(
            text = label,
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )
    }
}

